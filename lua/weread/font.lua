--[[
Reading font selection.

Honest scope: a terminal emulator owns its font, so nvim cannot change glyphs by
itself. What this module can do:
(诚实的边界：终端的字体由终端自己掌管，nvim 无法直接换字形。本模块能做的是：)

* list the CJK families actually installed (`fc-list`) and let you pick one;
* write a ready to include kitty snippet for that family, and apply it live when
  kitty's remote control happens to be enabled;
* print the equivalent snippet for other terminals;
* set `guifont`/`linespace` for real when nvim runs as a GUI (neovide, nvim-qt).
(列出真正装了的中文字体让你挑；为选中的字体写好可直接 include 的 kitty 片段，并在
 kitty 打开了远程控制时顺带实时应用；给出其它终端对应的配置片段；在 GUI（neovide、
 nvim-qt）里则直接设置 guifont/linespace)

The font choice is remembered in `preferences.json`.
(字体选择记在 preferences.json 里)
]]

local M = {}

---Fonts the reading app itself uses, best first. Used to sort candidates.
---(阅读类 App 自己会用的字体，越靠前越像书)
local PREFERRED = {
  "微信读书体",
  "source han serif",
  "思源宋体",
  "noto serif cjk",
  "songti",
  "simsun",
  "lxgw",
  "霞鹜文楷",
  "source han sans",
  "思源黑体",
  "noto sans cjk",
  "wenquanyi",
  "文泉驿",
  "noto sans mono cjk",
  "jetbrains maple",
  "sarasa",
  "更纱",
}

---@param name string
---@return integer score lower is better(越小越靠前)
local function score(name)
  local lowered = name:lower()
  for index, needle in ipairs(PREFERRED) do
    if lowered:find(needle, 1, true) then
      return index
    end
  end
  return #PREFERRED + 1
end

---Installed CJK families, deduplicated and sorted so book-ish serif faces come
---first.
---(已安装的中文字体，去重并按「像书的衬线体优先」排序)
---@return string[]
function M.installed()
  if vim.fn.executable("fc-list") ~= 1 then
    return {}
  end
  local result = vim.system({ "fc-list", ":lang=zh-cn", "family" }, { text = true }):wait()
  if result.code ~= 0 then
    return {}
  end

  local seen, families = {}, {}
  for line in (result.stdout or ""):gmatch("[^\n]+") do
    for name in line:gmatch("[^,]+") do
      name = vim.trim(name)
      if name ~= "" and not seen[name] then
        seen[name] = true
        families[#families + 1] = name
      end
    end
  end
  table.sort(families, function(left, right)
    local left_score, right_score = score(left), score(right)
    if left_score ~= right_score then
      return left_score < right_score
    end
    return left < right
  end)
  return families
end

---@return string|nil
function M.current()
  return require("weread.prefs").get("font")
end

---@return string
function M.snippet_path()
  return (vim.env.XDG_CONFIG_HOME or (vim.env.HOME .. "/.config")) .. "/kitty/weread-font.conf"
end

---Does kitty accept commands right now?
---(kitty 现在能接受命令吗)
---@return boolean
function M.kitty_remote()
  return (vim.env.KITTY_LISTEN_ON or "") ~= "" and vim.fn.executable("kitten") == 1
end

---@param windows table[]|nil kitty window ids
---@return boolean ok
local function kitty_reload(windows)
  if not M.kitty_remote() then
    return false
  end
  local args = { "kitten", "@", "load-config" }
  if windows and #windows > 0 then
    for _, id in ipairs(windows) do
      args[#args + 1] = "--match"
      args[#args + 1] = "id:" .. tostring(id)
    end
  end
  local result = vim.system(args, { text = true }):wait()
  return result.code == 0
end

---Config text to hand to a terminal.
---(交给终端的配置文本)
---@param family string
---@param opts table|nil { font_size, line_height }
---@return string
function M.snippet(family, opts)
  opts = opts or {}
  local lines = {
    "# generated by weread.nvim — :WeReadFont",
    "# 阅读字体（想换回来就删掉这一行，或在 kitty.conf 里注释掉 include）",
    "font_family      " .. family,
    "bold_font        auto",
    "italic_font      auto",
    "bold_italic_font auto",
  }
  if opts.font_size then
    lines[#lines + 1] = "font_size        " .. tostring(opts.font_size)
  end
  -- The app sets text on generous line height; terminals default to cramped.
  -- (App 的行距很宽，终端默认偏挤，想更像 App 可以打开这一行)
  lines[#lines + 1] = "# adjust_line_height 140%"
  return table.concat(lines, "\n") .. "\n"
end

---@param family string
---@return boolean ok
---@return string message
function M.apply(family, opts)
  opts = opts or {}
  local config = require("weread.config")
  config.ensure_dirs()

  -- GUI nvim can really change the font, so do that first.
  -- (GUI 版的 nvim 真能换字体，先设它)
  local gui = vim.g.neovide or vim.g.goneovim or (vim.fn.has("gui_running") == 1)
  if gui then
    local size = tonumber(opts.font_size) or 14
    pcall(function()
      vim.o.guifont = string.format("%s:h%d", family, size)
      vim.o.linespace = tonumber(opts.linespace) or 4
    end)
  end

  local path = M.snippet_path()
  vim.fn.mkdir(vim.fs.dirname(path), "p")
  local file = io.open(path, "wb")
  if not file then
    return false, "无法写入 " .. path
  end
  file:write(M.snippet(family, opts))
  file:close()

  require("weread.prefs").set("font", family)

  local lines = {
    string.format("weread: 已为阅读字体选择「%s」", family),
    "把它接进 kitty 需要一行 include（只需加一次）：",
    "    include " .. path,
    "然后按 ctrl+shift+F5 重载配置（或重启 kitty）。",
  }
  if M.kitty_remote() and kitty_reload() then
    lines[1] = lines[1] .. "（已尝试对当前 kitty 重载配置）"
  elseif not vim.g.neovide then
    lines[#lines + 1] = "提示：kitty 未开启 allow_remote_control，因此无法自动重载。"
  end
  return true, table.concat(lines, "\n")
end

---@param opts table|nil { font_size }
---@return boolean ok
function M.picker(opts)
  local families = M.installed()
  if #families == 0 then
    vim.notify("weread: 没找到中文字体（需要 fontconfig 的 fc-list）", vim.log.levels.WARN)
    return false
  end

  local current = M.current()
  local items = {}
  for _, family in ipairs(families) do
    local marker = family == current and "▶ " or "  "
    items[#items + 1] = { text = marker .. family, family = family }
  end

  require("weread.ui").select({
    title = "微信读书 · 阅读字体（按「像书」程度排序）",
    items = items,
    on_choice = function(item)
      local ok, message = M.apply(item.family, opts)
      vim.notify(message, ok and vim.log.levels.INFO or vim.log.levels.ERROR)
    end,
  })
  return true
end

---@return string
function M.status()
  local lines = { "阅读字体：" .. (M.current() or "未选择（跟随终端）") }
  local local_lines = {}
  lines[#lines + 1] = string.format(
    "kitty 远程控制：%s%s",
    M.kitty_remote() and "可用" or "不可用",
    M.kitty_remote() and "" or "（终端里执行 :WeReadFont 后按 ctrl+shift+F5 重载）"
  )
  lines[#lines + 1] = "kitty 片段：" .. M.snippet_path() .. (vim.fn.filereadable(M.snippet_path()) == 1 and "（已生成）" or "（未生成）")
  lines[#lines + 1] = "已安装中文字体：" .. #M.installed() .. " 个（:WeReadFont 可选择）"
  for _, line in ipairs(local_lines) do
    lines[#lines + 1] = line
  end
  return table.concat(lines, "\n")
end

return M
