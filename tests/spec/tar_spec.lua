--[[
Tests for weread.tar against a real tar produced by python's tarfile module
(tests/fixtures/images.tar, regenerated by scripts/gen_fixtures.py).
(tar 单测；夹具 tests/fixtures/images.tar 由 python tarfile 生成，属独立实现)
]]

local tar = require("weread.tar")

local FIXTURES = vim.fn.getcwd() .. "/tests/fixtures"

---Build one 512 byte tar header. The checksum is not verified by the reader,
---so zeros are fine.
---(构造一个 512 字节 tar 头；读取器不校验 checksum，填零即可)
---@param name string
---@param size integer
---@param typeflag string
---@param prefix string|nil
---@return string
local function header(name, size, typeflag, prefix)
  local block = {}
  local function put(from, to, value)
    local field = (value or ""):sub(1, to - from + 1)
    block[#block + 1] = field .. string.rep("\0", to - from + 1 - #field)
  end
  put(1, 100, name)
  put(101, 108, "0000644")
  put(109, 116, "0000000")
  put(117, 124, "0000000")
  put(125, 136, string.format("%011o", size))
  put(137, 148, "00000000000")
  put(149, 156, "0000000")
  put(157, 157, typeflag)
  put(158, 257, "")
  put(258, 263, "ustar\0")
  put(264, 265, "00")
  put(266, 297, "root")
  put(298, 329, "root")
  put(330, 337, "0000000")
  put(338, 345, "0000000")
  put(346, 500, prefix)
  put(501, 512, "")
  return table.concat(block)
end

---@param data string
---@return string
local function pad(data)
  local remainder = #data % 512
  if remainder == 0 then
    return data
  end
  return data .. string.rep("\0", 512 - remainder)
end

---@param name string
---@param data string
---@param typeflag string|nil
---@return string
local function entry(name, data, typeflag)
  return header(name, #data, typeflag or "0") .. pad(data)
end

describe("tar.parse", function()
  it("reads the fixture archive produced by python tarfile", function()
    local data = tar.read_file(FIXTURES .. "/images.tar")
    truthy(data, "fixture readable")

    local entries = tar.parse(data)
    eq(#entries, 3, "three files, the directory is skipped")

    local names = {}
    for _, entry in ipairs(entries) do
      names[#names + 1] = entry.name
    end
    table.sort(names)
    eq(names, {
      "36/epub_43208843_44",
      "36/epub_43208843_45",
      "36/epub_43208843_46",
    })
  end)

  it("keeps entry payloads intact", function()
    local entries = tar.parse(tar.read_file(FIXTURES .. "/images.tar"))
    local by_name = {}
    for _, entry in ipairs(entries) do
      by_name[entry.name] = entry
    end

    local png = by_name["36/epub_43208843_44"]
    eq(png.data:sub(1, 8), "\137PNG\r\n\26\n", "png magic preserved")
    eq(#png.data, png.size, "payload length matches the header size")

    local jpeg = by_name["36/epub_43208843_45"]
    eq(jpeg.data:sub(1, 3), "\255\216\255", "jpeg magic preserved")
  end)

  it("returns files only when asked", function()
    local data = tar.read_file(FIXTURES .. "/images.tar")
    local all = tar.parse(data, { files_only = false })
    -- the directory entry plus the three files
    -- (目录条目 + 3 个文件)
    eq(#all, 4)
  end)

  it("supports GNU long names", function()
    local long_name = string.rep("nested/", 20) .. "image" -- 127 chars, over the 100 byte field
    local archive = entry("././@LongLink", long_name .. "\0", "L")
      .. entry(long_name:sub(1, 99), "\137PNG\r\n\26\n" .. "payload")
      .. string.rep("\0", 1024)

    local entries = tar.parse(archive)
    eq(#entries, 1)
    eq(entries[1].name, long_name)
    eq(entries[1].data:sub(1, 8), "\137PNG\r\n\26\n")
  end)

  it("supports pax path records", function()
    local real_name = "very/deep/" .. string.rep("x", 120) .. "/photo"
    local pax_record = string.format("%d path=%s\n", #("path=" .. real_name .. "\n") + 4, real_name)
    local archive = entry("PaxHeaders/photo", pax_record, "x")
      .. entry("photo", "JPEG-ish")
      .. string.rep("\0", 1024)

    local entries = tar.parse(archive)
    eq(#entries, 1)
    eq(entries[1].name, real_name)
    eq(entries[1].data, "JPEG-ish")
  end)

  it("stops at the end-of-archive marker", function()
    local archive = entry("a/b.png", "one") .. string.rep("\0", 1024)
    eq(#tar.parse(archive), 1)
    eq(#tar.parse(""), 0)
    eq(#tar.parse("short"), 0)
  end)

  it("joins the ustar prefix field", function()
    local archive = header("photo", 5, "0", "36")
      .. pad("hello")
      .. string.rep("\0", 1024)
    local entries = tar.parse(archive)
    eq(#entries, 1)
    eq(entries[1].name, "36/photo")
  end)
end)

describe("tar.detect_type", function()
  it("recognises the fixture image types", function()
    local entries = tar.parse(tar.read_file(FIXTURES .. "/images.tar"))
    local detected = {}
    for _, entry in ipairs(entries) do
      local ext = tar.detect_type(entry.data)
      detected[entry.name] = ext
    end
    eq(detected["36/epub_43208843_44"], "png")
    eq(detected["36/epub_43208843_45"], "jpg")
    eq(detected["36/epub_43208843_46"], nil, "plain text is not an image")
  end)

  it("recognises the formats WeRead actually serves", function()
    eq(tar.detect_type("GIF89a-rest"), "gif")
    eq(tar.detect_type("RIFF\0\0\0\0WEBPVP8 "), "webp")
    eq(tar.detect_type("BM\0\0"), "bmp")
    eq(tar.detect_type('<svg xmlns="http://www.w3.org/2000/svg">'), "svg")
    eq(tar.detect_type("<?xml version=\"1.0\"?><svg></svg>"), "svg")
    eq(tar.detect_type(""), nil)
  end)
end)
